//! The zbuf generator: reads a schema (`buffers.zig`, see schema.zig)
//! as plain values and writes the readers, writers and structs for
//! its records. The generated code is written from templates that
//! look like the code they produce: a multi-line string with `$name`
//! placeholders, filled by `emit` from an argument struct. See the
//! README for the wire format.
const std = @import("std");
const schema = @import("schema");
const defs = @import("buffers");

/// A field with its wire position: `offset` in a table's header,
/// `fixed` for a packed field of fixed size.
const FieldInfo = struct {
    id: u32,
    name: []const u8,
    ty: schema.Type,
    len: schema.LenWidth = .u32,
    offset: u16 = 0,
    fixed: ?u32 = null,
};

/// The schema's `records`, tables and packed records alike: each
/// entry's kind is its type's, and only a table carries a message id.
const records: []const schema.Named = defs.records;

/// The enums the schema declares, by declaration name and in
/// declaration order: the one thing read off the schema file's
/// declarations rather than a list, so an EnumDef needs no registry
/// entry.
const enums: []const schema.Named = collectEnums();

fn collectEnums() []const schema.Named {
    comptime {
        var out: []const schema.Named = &.{};
        for (@typeInfo(defs).@"struct".decls) |d| {
            const v = @field(defs, d.name);
            if (@TypeOf(v) != schema.Type) continue;
            if (v.kind != .enum_) continue;
            out = out ++ &[_]schema.Named{.{ .name = d.name, .ty = v }};
        }
        return out;
    }
}

/// A schema mistake: named on stderr, and the run fails.
fn fail(msg: []const u8) error{InvalidSchema} {
    std.debug.print("{s}\n", .{msg});
    return error.InvalidSchema;
}

// =========================================================================
// Templates
// =========================================================================

/// Writes `template` with each placeholder filled from the field of
/// `args` of that name: `$name` up to the next non-identifier
/// character, or `${name}` where text follows. A string is written as
/// is, an integer in decimal. Generated Zig never contains `$`, so
/// nothing else in a template is special: braces stay as they are.
fn emit(w: anytype, template: []const u8, args: anytype) !void {
    var i: usize = 0;
    while (i < template.len) {
        const dollar = std.mem.indexOfScalarPos(u8, template, i, '$') orelse {
            try w.writeAll(template[i..]);
            return;
        };
        try w.writeAll(template[i..dollar]);
        var start = dollar + 1;
        var end = start;
        if (start < template.len and template[start] == '{') {
            start += 1;
            end = std.mem.indexOfScalarPos(u8, template, start, '}') orelse
                return error.BadTemplate;
            i = end + 1;
        } else {
            while (end < template.len and isIdent(template[end])) end += 1;
            i = end;
        }
        try writeArg(w, template[start..end], args);
    }
}

fn isIdent(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '_';
}

fn writeArg(w: anytype, name: []const u8, args: anytype) !void {
    inline for (@typeInfo(@TypeOf(args)).@"struct".fields) |f| {
        if (std.mem.eql(u8, f.name, name)) {
            const v = @field(args, f.name);
            switch (@typeInfo(@TypeOf(v))) {
                .int, .comptime_int => try w.print("{d}", .{v}),
                else => try w.writeAll(v),
            }
            return;
        }
    }
    std.debug.print("template placeholder without argument: ${s}\n", .{name});
    return error.BadTemplate;
}

pub fn main(init: std.process.Init) !void {
    const alloc = init.gpa;
    const io = init.io;

    var args_it = init.minimal.args.iterate();
    _ = args_it.next();
    const out_path = args_it.next() orelse "zbuf/buffers.gen.zig";

    // Write to a .tmp file first; rename to out_path only on success.
    // This guarantees the final file is always complete: a partial write
    // (crash, OOM, Ctrl-C) leaves the .tmp behind and the old .gen.zig intact.
    const tmp_path = try std.fmt.allocPrint(alloc, "{s}.tmp", .{out_path});
    defer alloc.free(tmp_path);
    const cwd = std.Io.Dir.cwd();
    errdefer cwd.deleteFile(io, tmp_path) catch {};

    {
        var file = try cwd.createFile(io, tmp_path, .{ .truncate = true });
        defer file.close(io);

        var buf: [4096]u8 = undefined;
        var fw = file.writer(io, &buf);
        var w = &fw.interface;
        try w.writeAll(
            \\// This file is generated by zbuf/gen.zig. Do not edit.
            \\const std = @import("std");
            \\const zbuf = @import("zbuf").zbuf;
            \\
            \\pub const Error = std.mem.Allocator.Error || zbuf.Error;
            \\pub const NullOffset: u32 = zbuf.NullOffset;
            \\
            \\pub const Ownership = zbuf.Ownership;
            \\
            \\
        );

        // Enums first: table fields name enum types.
        try emitEnumTypes(w);
        try emitTailHelpers(w);
        try emitMessageParser(w);

        for (records) |entry| {
            switch (entry.ty.kind) {
                .table => {
                    if (entry.id == 0) return fail("a table needs a message id");
                    try emitTable(alloc, entry.name, entry.ty, entry.id, w);
                },
                // No message id, no tail, no place in the message parser.
                .packed_ => try emitPacked(alloc, entry.name, entry.ty, w),
                else => return fail("records must be Table or Packed types"),
            }
        }
        try w.flush();
    } // file.close() fires here, before rename

    try cwd.rename(tmp_path, cwd, out_path, io);
    std.debug.print("generated {s}\n", .{out_path});
}

// =========================================================================
// Names and rules
// =========================================================================

/// The exported name of a Table or a Packed type.
fn recordName(ty: schema.Type) ![]const u8 {
    for (records) |entry| {
        if (entry.ty.sameRecord(ty)) return entry.name;
    }
    return fail("unknown record type: list it in `records`");
}

const tableName = recordName;
const packedName = recordName;

/// The name an enum type was bound to in buffers.zig; the generator
/// emits {Name}Enum for each.
fn enumName(ty: schema.Type) ![]const u8 {
    for (enums) |entry| {
        if (entry.ty.sameEnum(ty)) return entry.name;
    }
    return fail("enum type not found as a `pub const` in buffers.zig");
}

/// The Zig type of a scalar kind and its width.
const Scalar = struct {
    ty: []const u8,
    bytes: u16,
    bits: u16,
};

fn scalar(k: schema.Kind) Scalar {
    return switch (k) {
        .u8 => .{ .ty = "u8", .bytes = 1, .bits = 8 },
        .u16 => .{ .ty = "u16", .bytes = 2, .bits = 16 },
        .u32 => .{ .ty = "u32", .bytes = 4, .bits = 32 },
        .u64 => .{ .ty = "u64", .bytes = 8, .bits = 64 },
        else => unreachable,
    };
}

/// Bytes per element of a table's array: scalars inline, tables as
/// u32 offsets.
fn arrayElemSize(child: schema.Type) u16 {
    return if (child.kind == .table) 4 else scalar(child.kind).bytes;
}

fn hasBoolOverlay(infos: []const FieldInfo, field_id: u32) bool {
    for (infos) |other| {
        if (other.ty.kind != .bool) continue;
        if (other.ty.bool_field_id == field_id) return true;
    }
    return false;
}

fn findFieldInfoById(infos: []const FieldInfo, field_id: u32) ?FieldInfo {
    for (infos) |info| {
        if (info.id == field_id) return info;
    }
    return null;
}

/// The rules a Table's fields must follow: no packed record, only
/// scalars or tables as array elements, and every bool on a bit of a
/// scalar field that exists, with no two bools on the same bit.
fn requireTableLayoutValid(infos: []const FieldInfo) !void {
    for (infos) |info| {
        switch (info.ty.kind) {
            .packed_ => return fail("a Packed cannot be a Table's field"),
            .array => switch (info.ty.elem().kind) {
                .u8, .u16, .u32, .u64, .table => {},
                else => return fail("unsupported array child kind"),
            },
            else => {},
        }
    }
    for (infos, 0..) |info, i| {
        if (info.ty.kind != .bool) continue;
        const bits_field = findFieldInfoById(infos, info.ty.bool_field_id) orelse
            return fail("Bool field references unknown backing field id");
        if (!bits_field.ty.isScalar())
            return fail("bool backing field must be U8/U16/U32/U64");
        if (info.ty.bool_bit >= scalar(bits_field.ty.kind).bits)
            return fail("Bool field bit index exceeds backing field width");
        // Every pair once: only the later fields are compared.
        for (infos[i + 1 ..]) |other| {
            if (other.ty.kind != .bool) continue;
            if (other.ty.bool_field_id != info.ty.bool_field_id) continue;
            if (other.ty.bool_bit != info.ty.bool_bit) continue;
            return fail("duplicate Bool mapping to same backing field bit");
        }
    }
}

/// The rules a Packed must follow.
fn requirePackedLayoutValid(infos: []const FieldInfo) !void {
    for (infos, 0..) |info, i| {
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64, .enum_ => {},
            .bytes => if (info.len == .rest and i + 1 != infos.len)
                return fail("a `.rest` Bytes must be the last field of a Packed"),
            .array => {
                if (info.len == .rest)
                    return fail("an Array's count cannot be `.rest`");
                switch (info.ty.elem().kind) {
                    .u8, .u16, .u32, .u64, .enum_, .packed_ => {},
                    else => return fail("Array elements in a Packed must be scalars or a Packed"),
                }
            },
            .packed_ => if (schema.packedFixedSize(info.ty) == null)
                return fail("a nested Packed must be fixed size"),
            .table => return fail("a Table cannot be a Packed's field"),
            .bool => return fail("a Packed has no bool fields"),
        }
    }
}

/// The fields of a record in wire order, with their table slot
/// offsets and packed fixed sizes. Caller frees.
fn layout(alloc: std.mem.Allocator, ty: schema.Type) ![]FieldInfo {
    const fields = try schema.sortFieldsById(alloc, ty.fields);
    defer alloc.free(fields);
    const infos = try alloc.alloc(FieldInfo, fields.len);
    errdefer alloc.free(infos);
    var offset: u16 = 2; // a table's size_bytes
    for (fields, infos) |f, *info| {
        info.* = .{
            .id = f.id,
            .name = f.name,
            .ty = f.ty,
            .len = f.len,
            .offset = offset,
            .fixed = schema.packedFixedSize(f.ty),
        };
        if (f.ty.kind != .packed_) offset += schema.slotSize(f.ty);
    }
    return infos;
}

// =========================================================================
// Shared prologue: enums, tail helpers, message parser
// =========================================================================

fn emitEnumTypes(w: anytype) !void {
    for (enums) |entry| {
        const variants = entry.ty.variants;
        // Tags fit in u8 and are unique.
        for (variants, 0..) |v, i| {
            if (v.tag >= 256) return fail("enum tag exceeds u8 range");
            for (variants[i + 1 ..]) |o| {
                if (o.tag == v.tag) return fail("duplicate enum tag");
            }
        }
        try emit(w,
            \\pub const ${name}Enum = enum(u8) {
            \\
        , .{ .name = entry.name });
        for (variants) |v| {
            try emit(w,
                \\    $name = $tag,
                \\
            , .{ .name = v.name, .tag = v.tag });
        }
        try w.writeAll(
            \\    _,
            \\};
            \\
            \\
        );
    }
}

fn emitTailHelpers(w: anytype) !void {
    // addTail tags an existing buffer with the type-id tail. The caller must
    // ensure the root table sits at payload offset 0. marshalRoot serializes
    // a *Struct into a fresh, self-contained payload that parseRoot can
    // read: marshalTo writes the body at offset 0, addTail appends the
    // type-id tail (read off the struct's own TABLE_ID). Caller owns the
    // returned slice.
    try w.writeAll(
        \\pub fn addTail(alloc: std.mem.Allocator, buf: *std.ArrayList(u8), comptime T: type, offset: u32) Error!void {
        \\    try zbuf.appendMessageTail(buf, alloc, T.TABLE_ID, offset);
        \\}
        \\
        \\pub fn marshalRoot(alloc: std.mem.Allocator, value: anytype) Error![]u8 {
        \\    if (!@hasDecl(@TypeOf(value), "TABLE_ID")) @compileError("marshalRoot expects a generated *Struct with a TABLE_ID; got " ++ @typeName(@TypeOf(value)));
        \\    var buf: std.ArrayList(u8) = .empty;
        \\    errdefer buf.deinit(alloc);
        \\    const offset = try value.marshalTo(alloc, &buf);
        \\    try addTail(alloc, &buf, @TypeOf(value), offset);
        \\    return buf.toOwnedSlice(alloc);
        \\}
        \\
        \\pub fn parseTail(buf: []const u8) Error!zbuf.MessageTail {
        \\    return zbuf.readMessageTail(buf);
        \\}
        \\
        \\pub fn parseMessageWithTail(buf: []const u8) Error!MessageReader {
        \\    const tail = try zbuf.readMessageTail(buf);
        \\    const payload_buf = buf[0 .. buf.len - zbuf.message_tail_size];
        \\    return switch (tail.table_id) {
        \\
    );
    for (records) |entry| {
        if (entry.ty.kind != .table) continue;
        try emit(w,
            \\        ${name}Reader.TABLE_ID => .{ .$name = try ${name}Reader.init(payload_buf, 0) },
            \\
        , .{ .name = entry.name });
    }
    try w.writeAll(
        \\        else => zbuf.Error.Invalid,
        \\    };
        \\}
        \\
        \\
    );
}

fn emitMessageParser(w: anytype) !void {
    try w.writeAll("pub const MessageReader = union(enum) {\n");
    for (records) |entry| {
        if (entry.ty.kind != .table) continue;
        try emit(w,
            \\    $name: ${name}Reader,
            \\
        , .{ .name = entry.name });
    }
    try w.writeAll("};\n\n");
}

// =========================================================================
// Tables
// =========================================================================

fn emitTable(alloc: std.mem.Allocator, table_name: []const u8, ty: schema.Type, table_id: u16, w: anytype) !void {
    const infos = try layout(alloc, ty);
    defer alloc.free(infos);
    try requireTableLayoutValid(infos);
    // The header is `size_bytes` (u16) at offset 0 then the slots.
    const size_bytes: u16 = if (infos.len == 0) 2 else blk: {
        const last = infos[infos.len - 1];
        break :blk last.offset + schema.slotSize(last.ty);
    };

    try emitStructType(alloc, table_name, table_id, infos, w);
    try emitTableReader(alloc, table_name, table_id, size_bytes, infos, w);
    try emitTableWriter(alloc, table_name, table_id, size_bytes, infos, w);
}

/// The generated reader wraps a `zbuf.Table` and reads each field's
/// slot through it; the slot offsets are the one thing the schema
/// decides. Table arrays are read as their children's offsets.
fn emitTableReader(alloc: std.mem.Allocator, table_name: []const u8, table_id: u16, size_bytes: u16, infos: []const FieldInfo, w: anytype) !void {
    try emit(w,
        \\pub const ${name}Reader = struct {
        \\    const Self = @This();
        \\    t: zbuf.Table,
        \\
        \\    pub const TABLE_ID: u16 = $table_id;
        \\    pub const SIZE_BYTES: u16 = $size_bytes;
        \\
        \\    pub fn parseRoot(buf: []const u8) Error!Self {
        \\        return .{ .t = try zbuf.Table.parseRoot(buf, TABLE_ID) };
        \\    }
        \\
        \\    pub fn init(buf: []const u8, base: u32) Error!Self {
        \\        return .{ .t = try zbuf.Table.init(buf, base) };
        \\    }
        \\
        \\
    , .{ .name = table_name, .table_id = table_id, .size_bytes = size_bytes });

    for (infos) |info| {
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64 => {
                const s = scalar(info.ty.kind);
                try emit(w,
                    \\    pub fn $getter(self: Self) $ty {
                    \\        return self.t.scalar($ty, $offset);
                    \\    }
                    \\
                    \\
                , .{ .getter = getter, .ty = s.ty, .offset = info.offset });
                if (hasBoolOverlay(infos, info.id)) {
                    try emit(w,
                        \\    pub fn ${getter}HasBit(self: Self, bit_index: u32) bool {
                        \\        return self.t.hasBit($ty, $offset, bit_index);
                        \\    }
                        \\
                        \\
                    , .{ .getter = getter, .ty = s.ty, .offset = info.offset });
                }
            },
            .bytes => try emit(w,
                \\    pub fn $getter(self: Self) []const u8 {
                \\        return self.t.bytes($offset);
                \\    }
                \\
                \\
            , .{ .getter = getter, .offset = info.offset }),
            .array => {
                const child = info.ty.elem();
                try emit(w,
                    \\    pub fn ${getter}Len(self: Self) u32 {
                    \\        return self.t.arrayLen($offset, $elem_size);
                    \\    }
                    \\
                    \\
                , .{ .getter = getter, .offset = info.offset, .elem_size = arrayElemSize(child) });
                if (child.kind == .table) {
                    try emit(w,
                        \\    pub fn ${getter}At(self: Self, i: u32) Error!${child}Reader {
                        \\        return ${child}Reader.init(self.t.buf, try self.t.arrayChild($offset, i));
                        \\    }
                        \\
                        \\
                    , .{ .getter = getter, .child = try tableName(child), .offset = info.offset });
                } else {
                    try emit(w,
                        \\    pub fn ${getter}At(self: Self, i: u32) Error!$ty {
                        \\        return self.t.arrayScalar($ty, $offset, i);
                        \\    }
                        \\
                        \\    pub fn ${getter}ToSliceAlloc(self: Self, alloc: std.mem.Allocator) Error![]$ty {
                        \\        return self.t.arrayToSliceAlloc($ty, $offset, alloc);
                        \\    }
                        \\
                        \\
                    , .{ .getter = getter, .ty = scalar(child.kind).ty, .offset = info.offset });
                }
            },
            .table => try emit(w,
                \\    pub fn $getter(self: Self) ?${child}Reader {
                \\        const off = self.t.child($offset) orelse return null;
                \\        return ${child}Reader.init(self.t.buf, off) catch null;
                \\    }
                \\
                \\
            , .{ .getter = getter, .child = try tableName(info.ty), .offset = info.offset }),
            .bool => {
                const bits_field = findFieldInfoById(infos, info.ty.bool_field_id).?;
                try emit(w,
                    \\    pub fn $getter(self: Self) bool {
                    \\        return self.t.hasBit($ty, $offset, $bit);
                    \\    }
                    \\
                    \\
                , .{ .getter = getter, .ty = scalar(bits_field.ty.kind).ty, .offset = bits_field.offset, .bit = info.ty.bool_bit });
            },
            .enum_ => try emit(w,
                \\    pub fn $getter(self: Self) ${enum}Enum {
                \\        return @enumFromInt(self.t.scalar(u8, $offset));
                \\    }
                \\
                \\
            , .{ .getter = getter, .@"enum" = try enumName(info.ty), .offset = info.offset }),
            .packed_ => unreachable,
        }
    }

    // cloneInto: the record re-serialized into `out` through a writer.
    try emit(w,
        \\    pub fn cloneInto(self: Self, alloc: std.mem.Allocator, out: *std.ArrayList(u8)) Error!u32 {
        \\        var writer = try ${name}Writer.initWithBuf(alloc, out);
        \\
    , .{ .name = table_name });
    for (infos) |info| {
        const setter = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(setter);
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        const args = .{ .setter = setter, .getter = getter };
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64, .bytes, .bool, .enum_ => try emit(w,
                \\        try writer.set$setter(self.$getter());
                \\
            , args),
            .table => try emit(w,
                \\        if (self.$getter()) |child| {
                \\            const child_off = try child.cloneInto(alloc, out);
                \\            try writer.set$setter(child_off);
                \\        }
                \\
            , args),
            .array => if (info.ty.elem().kind == .table) {
                try emit(w,
                    \\        const count_$getter: u32 = self.${getter}Len();
                    \\        if (count_$getter != 0) {
                    \\            var child_offsets_$getter = try alloc.alloc(u32, @intCast(count_$getter));
                    \\            defer alloc.free(child_offsets_$getter);
                    \\            var i_$getter: u32 = 0;
                    \\            while (i_$getter < count_$getter) : (i_$getter += 1) {
                    \\                const child = try self.${getter}At(i_$getter);
                    \\                child_offsets_$getter[@intCast(i_$getter)] = try child.cloneInto(alloc, out);
                    \\            }
                    \\            try writer.set$setter(child_offsets_$getter);
                    \\        }
                    \\
                , args);
            } else {
                try emit(w,
                    \\        const values_$getter = try self.${getter}ToSliceAlloc(alloc);
                    \\        defer alloc.free(values_$getter);
                    \\        if (values_$getter.len > 0) try writer.set$setter(values_$getter);
                    \\
                , args);
            },
            .packed_ => unreachable,
        }
    }
    try w.writeAll(
        \\        const result = try writer.finish();
        \\        return result.offset;
        \\    }
        \\
        \\
    );

    // verify(): the header and every field's data lie within the payload.
    try w.writeAll(
        \\    pub fn verify(self: Self) Error!void {
        \\        try self.t.verifyHeader();
        \\
    );
    for (infos) |info| {
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        switch (info.ty.kind) {
            .bytes => try emit(w, "        try self.t.verifyBytes($offset);\n", .{ .offset = info.offset }),
            .array => {
                const child = info.ty.elem();
                try emit(w, "        try self.t.verifyArray($offset, $elem_size);\n", .{ .offset = info.offset, .elem_size = arrayElemSize(child) });
                if (child.kind == .table) {
                    try emit(w,
                        \\        for (0..self.${getter}Len()) |i| {
                        \\            try (try self.${getter}At(@intCast(i))).verify();
                        \\        }
                        \\
                    , .{ .getter = getter });
                }
            },
            .table => try emit(w,
                \\        if (self.$getter()) |child_view| try child_view.verify();
                \\
            , .{ .getter = getter }),
            else => {},
        }
    }
    try w.writeAll("    }\n");

    try emitToStruct(alloc, table_name, infos, w);
    try w.writeAll("};\n\n");
}

/// The generated writer wraps a `zbuf.TableWriter` and patches each
/// field's slot through it; the Buffer it finishes into is the
/// library's, typed by the reader.
fn emitTableWriter(alloc: std.mem.Allocator, table_name: []const u8, table_id: u16, size_bytes: u16, infos: []const FieldInfo, w: anytype) !void {
    try emit(w,
        \\pub const ${name}Buffer = zbuf.Buffer(${name}Reader);
        \\
        \\pub const ${name}Writer = struct {
        \\    const Self = @This();
        \\    w: zbuf.TableWriter,
        \\
        \\    pub const TABLE_ID: u16 = $table_id;
        \\    pub const SIZE_BYTES: u16 = $size_bytes;
        \\    /// Slots of nested tables, null until set.
        \\    const child_slots = [_]u16{
    , .{ .name = table_name, .table_id = table_id, .size_bytes = size_bytes });
    var first = true;
    for (infos) |info| {
        if (info.ty.kind != .table) continue;
        try emit(w, "$sep$offset", .{ .sep = if (first) " " else ", ", .offset = info.offset });
        first = false;
    }
    try emit(w,
        \\$sep};
        \\
        \\    pub fn initWithBuf(alloc: std.mem.Allocator, buf: *std.ArrayList(u8)) Error!Self {
        \\        return .{ .w = try zbuf.TableWriter.initWithBuf(alloc, buf, SIZE_BYTES, &child_slots) };
        \\    }
        \\
        \\    pub fn init(alloc: std.mem.Allocator) Error!Self {
        \\        return .{ .w = try zbuf.TableWriter.init(alloc, SIZE_BYTES, &child_slots) };
        \\    }
        \\
        \\
    , .{ .sep = if (first) "" else " " });

    for (infos) |info| {
        const setter = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(setter);
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64 => {
                const s = scalar(info.ty.kind);
                try emit(w,
                    \\    pub fn set$setter(self: *Self, v: $ty) Error!void {
                    \\        return self.w.setScalar($ty, $offset, v);
                    \\    }
                    \\
                    \\
                , .{ .setter = setter, .ty = s.ty, .offset = info.offset });
                if (hasBoolOverlay(infos, info.id)) {
                    try emit(w,
                        \\    pub fn ${getter}SetBit(self: *Self, bit_index: u32) Error!void {
                        \\        return self.w.bitSet($ty, $offset, bit_index);
                        \\    }
                        \\
                        \\    pub fn ${getter}ClearBit(self: *Self, bit_index: u32) Error!void {
                        \\        return self.w.bitClear($ty, $offset, bit_index);
                        \\    }
                        \\
                        \\    pub fn ${getter}HasBit(self: *Self, bit_index: u32) Error!bool {
                        \\        return self.w.bitHas($ty, $offset, bit_index);
                        \\    }
                        \\
                        \\
                    , .{ .getter = getter, .ty = s.ty, .offset = info.offset });
                }
            },
            .bytes => try emit(w,
                \\    pub fn set$setter(self: *Self, data: []const u8) Error!void {
                \\        return self.w.setBytes($offset, data);
                \\    }
                \\
                \\
            , .{ .setter = setter, .offset = info.offset }),
            .array => {
                const child = info.ty.elem();
                const s = scalar(if (child.kind == .table) .u32 else child.kind);
                try emit(w,
                    \\    pub fn set$setter(self: *Self, values: []const $ty) Error!void {
                    \\        return self.w.setArray($ty, $offset, values);
                    \\    }
                    \\
                    \\
                , .{ .setter = setter, .ty = s.ty, .offset = info.offset });
            },
            .table => try emit(w,
                \\    pub fn set$setter(self: *Self, child_off: u32) Error!void {
                \\        return self.w.setChild($offset, child_off);
                \\    }
                \\
                \\
            , .{ .setter = setter, .offset = info.offset }),
            .bool => {
                const bits_field = findFieldInfoById(infos, info.ty.bool_field_id).?;
                try emit(w,
                    \\    pub fn set$setter(self: *Self, v: bool) Error!void {
                    \\        return self.w.setBit($ty, $offset, $bit, v);
                    \\    }
                    \\
                    \\
                , .{ .setter = setter, .ty = scalar(bits_field.ty.kind).ty, .offset = bits_field.offset, .bit = info.ty.bool_bit });
            },
            .enum_ => try emit(w,
                \\    pub fn set$setter(self: *Self, v: ${enum}Enum) Error!void {
                \\        return self.w.setScalar(u8, $offset, @intFromEnum(v));
                \\    }
                \\
                \\
            , .{ .setter = setter, .@"enum" = try enumName(info.ty), .offset = info.offset }),
            .packed_ => unreachable,
        }
    }

    // set() applies the fields given in a struct literal in one call.
    try w.writeAll(
        \\    pub fn set(self: *Self, values: anytype) Error!void {
        \\        const Values = @TypeOf(values);
        \\        if (@typeInfo(Values) != .@"struct") {
        \\            @compileError("set() expects a struct literal like .{ .field = value }");
        \\        }
        \\
    );
    for (infos) |info| {
        const setter = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(setter);
        try emit(w,
            \\        if (@hasField(Values, "$field")) try self.set$setter(@field(values, "$field"));
            \\
        , .{ .field = info.name, .setter = setter });
    }
    try emit(w,
        \\    }
        \\
        \\    pub fn finish(self: *Self) Error!${name}Buffer {
        \\        return self.w.finish(${name}Buffer);
        \\    }
        \\
        \\    /// Root must be at payload offset 0: initialize the root writer
        \\    /// first on an empty buffer.
        \\    pub fn finishWithTail(self: *Self) Error!${name}Buffer {
        \\        return self.w.finishWithTail(${name}Buffer, TABLE_ID);
        \\    }
        \\
        \\    pub fn deinit(self: *Self) void {
        \\        self.w.deinit();
        \\    }
        \\};
        \\
        \\
    , .{ .name = table_name });
}

// =========================================================================
// Structs: the owned form of a Table or a Packed
// =========================================================================

/// The Zig type a field takes in its record's struct.
fn structFieldType(alloc: std.mem.Allocator, ty: schema.Type) ![]const u8 {
    return switch (ty.kind) {
        .u8, .u16, .u32, .u64 => try alloc.dupe(u8, scalar(ty.kind).ty),
        .bool => try alloc.dupe(u8, "bool"),
        .enum_ => try std.fmt.allocPrint(alloc, "{s}Enum", .{try enumName(ty)}),
        .bytes => try alloc.dupe(u8, "[]const u8"),
        .array => switch (ty.elem().kind) {
            .u8, .u16, .u32, .u64 => try std.fmt.allocPrint(alloc, "[]{s}", .{scalar(ty.elem().kind).ty}),
            else => try std.fmt.allocPrint(alloc, "[]{s}Struct", .{try recordName(ty.elem())}),
        },
        .table => try std.fmt.allocPrint(alloc, "?{s}Struct", .{try tableName(ty)}),
        .packed_ => try std.fmt.allocPrint(alloc, "{s}Struct", .{try packedName(ty)}),
    };
}

/// A struct field's default: zero, false, null, empty, or an empty
/// nested record.
fn structFieldDefault(ty: schema.Type) []const u8 {
    return switch (ty.kind) {
        .u8, .u16, .u32, .u64 => "0",
        .bool => "false",
        .enum_ => "@enumFromInt(0)",
        .bytes, .array => "&.{}",
        .table => "null",
        .packed_ => ".{}",
    };
}

/// {Name}Struct: the fields as owned Zig values with `deinit`,
/// `destroy`, `clone` and `marshalTo`. A Table's has its TABLE_ID and
/// marshals field by field through its writer's setters; a Packed's
/// (`table_id` null) marshals in one positional `set`. Decoding from a
/// Reader lives on the Reader (toStruct/toStructValue), whose getters
/// both record kinds name the same way.
fn emitStructType(alloc: std.mem.Allocator, table_name: []const u8, table_id: ?u16, infos: []const FieldInfo, w: anytype) !void {
    try emit(w, "pub const ${name}Struct = struct {\n", .{ .name = table_name });
    // The message's type id, mirrored from {Name}Reader. marshalRoot reads it
    // off the struct, so callers serialize a root payload without naming the
    // Reader — and a struct that lacks it fails marshalRoot at comptime.
    if (table_id) |id| try emit(w, "    pub const TABLE_ID: u16 = $id;\n", .{ .id = id });

    for (infos) |info| {
        const ty_name = try structFieldType(alloc, info.ty);
        defer alloc.free(ty_name);
        try emit(w, "    $field: $ty = $default,\n", .{ .field = info.name, .ty = ty_name, .default = structFieldDefault(info.ty) });
    }

    // deinit: free all allocated fields.
    var has_owned_fields = false;
    for (infos) |info| switch (info.ty.kind) {
        .bytes, .array, .table, .packed_ => has_owned_fields = true,
        else => {},
    };
    try emit(w, "    pub fn deinit(self: *${name}Struct, alloc: std.mem.Allocator) void {\n", .{ .name = table_name });
    if (!has_owned_fields) {
        try w.writeAll("        _ = self;\n        _ = alloc;\n");
    }
    for (infos) |info| {
        const args = .{ .field = info.name };
        switch (info.ty.kind) {
            .bytes => try emit(w,
                \\        alloc.free(self.$field);
                \\        self.$field = &.{};
                \\
            , args),
            .array => {
                if (!info.ty.elem().isScalar()) {
                    try emit(w, "        for (self.$field) |*_b| _b.deinit(alloc);\n", args);
                }
                try emit(w,
                    \\        alloc.free(self.$field);
                    \\        self.$field = &.{};
                    \\
                , args);
            },
            .table => try emit(w,
                \\        if (self.$field) |*_bf| _bf.deinit(alloc);
                \\        self.$field = null;
                \\
            , args),
            .packed_ => try emit(w, "        self.$field.deinit(alloc);\n", args),
            else => {},
        }
    }
    try emit(w,
        \\    }
        \\
        \\    pub fn destroy(self: *${name}Struct, alloc: std.mem.Allocator) void {
        \\        self.deinit(alloc);
        \\        alloc.destroy(self);
        \\    }
        \\
        \\    fn cloneValue(self: ${name}Struct, alloc: std.mem.Allocator) Error!${name}Struct {
        \\
    , .{ .name = table_name });
    try emitCopy(alloc, table_name, infos, .clone, w);
    try emit(w,
        \\    }
        \\
        \\    pub fn clone(self: ${name}Struct, alloc: std.mem.Allocator) Error!*${name}Struct {
        \\        const ptr = try alloc.create(${name}Struct);
        \\        errdefer alloc.destroy(ptr);
        \\        ptr.* = try self.cloneValue(alloc);
        \\        return ptr;
        \\    }
        \\
        \\    pub fn marshalTo(self: ${name}Struct, alloc: std.mem.Allocator, out: *std.ArrayList(u8)) Error!u32 {
        \\
    , .{ .name = table_name });
    if (table_id == null) {
        try emit(w,
            \\        var writer = ${name}Writer.initWithBuf(alloc, out);
            \\        try writer.set(self);
            \\        return writer.finish();
            \\    }
            \\};
            \\
            \\
        , .{ .name = table_name });
        return;
    }
    try emit(w, "        var writer = try ${name}Writer.initWithBuf(alloc, out);\n", .{ .name = table_name });
    // Pass 1: scalars (incl. any flags backing field), tables, arrays — in
    // declaration order. Bool overlays are deferred to pass 2, so each
    // folds its bit into the backing scalar written here rather than
    // being overwritten by it: a fresh `*Struct{ .dropped = true }`
    // serializes correctly with no bit math.
    for (infos) |info| {
        if (info.ty.kind == .bool) continue;
        const setter = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(setter);
        const args = .{ .setter = setter, .field = info.name };
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64, .bytes, .enum_ => try emit(w,
                \\        try writer.set$setter(self.$field);
                \\
            , args),
            .table => try emit(w,
                \\        if (self.$field) |child| {
                \\            const child_off = try child.marshalTo(alloc, out);
                \\            try writer.set$setter(child_off);
                \\        }
                \\
            , args),
            .array => if (info.ty.elem().kind == .table) {
                try emit(w,
                    \\        if (self.$field.len > 0) {
                    \\            const offsets = try alloc.alloc(u32, self.$field.len);
                    \\            defer alloc.free(offsets);
                    \\            for (self.$field, 0..) |child, ci| {
                    \\                offsets[ci] = try child.marshalTo(alloc, out);
                    \\            }
                    \\            try writer.set$setter(offsets);
                    \\        }
                    \\
                , args);
            } else {
                try emit(w,
                    \\        if (self.$field.len > 0) try writer.set$setter(self.$field);
                    \\
                , args);
            },
            .bool, .packed_ => unreachable,
        }
    }
    for (infos) |info| {
        if (info.ty.kind != .bool) continue;
        const setter = try schema.camelNameCapitalized(alloc, info.name);
        defer alloc.free(setter);
        try emit(w, "        try writer.set$setter(self.$field);\n", .{ .setter = setter, .field = info.name });
    }
    try w.writeAll(
        \\        const result = try writer.finish();
        \\        return result.offset;
        \\    }
        \\};
        \\
        \\
    );
}

/// toStructValue / toStruct on a Reader: the record copied into its owned
/// struct, through the getters both record kinds name the same way.
/// toStructValue is also public so a caller that wants a value-form
/// copy can avoid the pointer hop of toStruct.
fn emitToStruct(alloc: std.mem.Allocator, table_name: []const u8, infos: []const FieldInfo, w: anytype) !void {
    try emit(w, "    pub fn toStructValue(self: Self, alloc: std.mem.Allocator) Error!${name}Struct {\n", .{ .name = table_name });
    try emitCopy(alloc, table_name, infos, .decode, w);
    try emit(w,
        \\    }
        \\    pub fn toStruct(self: Self, alloc: std.mem.Allocator) Error!*${name}Struct {
        \\        const ptr = try alloc.create(${name}Struct);
        \\        errdefer alloc.destroy(ptr);
        \\        ptr.* = try self.toStructValue(alloc);
        \\        return ptr;
        \\    }
        \\
    , .{ .name = table_name });
}

/// The body that builds a fresh struct `s` from `self`: a Reader's
/// getters (`.decode`, for toStructValue) or a struct's own fields
/// (`.clone`, for cloneValue). The steps are the same, scalars inline,
/// then every owned field after the errdefer, so one emitter serves
/// both with the access spelled per mode.
const CopyMode = enum { decode, clone };

fn emitCopy(alloc: std.mem.Allocator, table_name: []const u8, infos: []const FieldInfo, mode: CopyMode, w: anytype) !void {
    // Step 1: inline-init scalars, bools and enums (no allocation).
    try emit(w, "        var s = ${name}Struct{\n", .{ .name = table_name });
    for (infos) |info| {
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64, .bool, .enum_ => switch (mode) {
                .decode => try emit(w, "            .$field = self.$getter(),\n", .{ .field = info.name, .getter = getter }),
                .clone => try emit(w, "            .$field = self.$field,\n", .{ .field = info.name }),
            },
            else => {},
        }
    }
    // Step 2: errdefer before any allocation so partial failures are safe.
    try w.writeAll(
        \\        };
        \\        errdefer s.deinit(alloc);
        \\
    );
    // Step 3: bytes fields — dupe the slice.
    for (infos) |info| {
        if (info.ty.kind != .bytes) continue;
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        switch (mode) {
            .decode => try emit(w, "        s.$field = try alloc.dupe(u8, self.$getter());\n", .{ .field = info.name, .getter = getter }),
            .clone => try emit(w, "        s.$field = try alloc.dupe(u8, self.$field);\n", .{ .field = info.name }),
        }
    }
    // Step 4: scalar arrays — one allocation and copy.
    for (infos) |info| {
        if (info.ty.kind != .array or !info.ty.elem().isScalar()) continue;
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        switch (mode) {
            .decode => try emit(w, "        s.$field = try self.${getter}ToSliceAlloc(alloc);\n", .{ .field = info.name, .getter = getter }),
            .clone => try emit(w, "        s.$field = try alloc.dupe($ty, self.$field);\n", .{ .field = info.name, .ty = scalar(info.ty.elem().kind).ty }),
        }
    }
    // Step 5: record arrays — alloc the slice, zero-init, then copy each child by value.
    for (infos) |info| {
        if (info.ty.kind != .array or info.ty.elem().isScalar()) continue;
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        const args = .{ .field = info.name, .getter = getter, .child = try recordName(info.ty.elem()) };
        switch (mode) {
            .decode => try emit(w,
                \\        {
                \\            const _cnt = self.${getter}Len();
                \\            s.$field = try alloc.alloc(${child}Struct, @intCast(_cnt));
                \\            @memset(s.$field, .{});
                \\            for (0.._cnt) |_i| {
                \\                const _child = try self.${getter}At(@intCast(_i));
                \\                s.$field[_i] = try _child.toStructValue(alloc);
                \\            }
                \\        }
                \\
            , args),
            .clone => try emit(w,
                \\        {
                \\            s.$field = try alloc.alloc(${child}Struct, self.$field.len);
                \\            @memset(s.$field, .{});
                \\            for (self.$field, 0..) |_child, _i| {
                \\                s.$field[_i] = try _child.cloneValue(alloc);
                \\            }
                \\        }
                \\
            , args),
        }
    }
    // Step 6: nested records: an optional table, an inline packed one.
    for (infos) |info| {
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        const args = .{ .field = info.name, .getter = getter };
        switch (info.ty.kind) {
            .table => switch (mode) {
                .decode => try emit(w,
                    \\        if (self.$getter()) |_child| {
                    \\            s.$field = try _child.toStructValue(alloc);
                    \\        }
                    \\
                , args),
                .clone => try emit(w,
                    \\        if (self.$field) |_child| {
                    \\            s.$field = try _child.cloneValue(alloc);
                    \\        }
                    \\
                , args),
            },
            .packed_ => switch (mode) {
                .decode => try emit(w, "        s.$field = try self.$getter().toStructValue(alloc);\n", args),
                .clone => try emit(w, "        s.$field = try self.$field.cloneValue(alloc);\n", args),
            },
            else => {},
        }
    }
    try w.writeAll("        return s;\n");
}

// =========================================================================
// Packed records (schema.Packed). See the schema for the wire rules; in
// short: fields lie one after another in id order with nothing between
// them, a Bytes is [len][bytes], an Array is [count][count × element],
// a Bytes with `.len = .rest` runs to the end of the record, a nested
// Packed sits inline. The generated reader keeps only the record's
// slice: a field's start is a constant while every field before it is
// fixed-size, and a small function after that, so nothing is walked or
// stored up front. The writer appends every field of a struct in order
// through a `zbuf.PackedWriter`.
// =========================================================================

fn emitPacked(alloc: std.mem.Allocator, name: []const u8, ty: schema.Type, w: anytype) !void {
    const infos = try layout(alloc, ty);
    defer alloc.free(infos);
    try requirePackedLayoutValid(infos);

    try emitStructType(alloc, name, null, infos, w);
    try emitPackedReader(alloc, name, ty, infos, w);
    try emitPackedWriter(name, ty, infos, w);
}

fn lenWidthName(width: schema.LenWidth) []const u8 {
    return switch (width) {
        .u8 => ".u8",
        .u16 => ".u16",
        .u32 => ".u32",
        .rest => unreachable,
    };
}

/// Where each field starts: a constant while every field before it is
/// fixed-size, and from the first variable field on a function that
/// adds the previous field's length to its start. No walk at `init`:
/// a packed record is trusted (see zbuf.load), so a field is read
/// where the layout puts it, when it is asked for.
const FieldPos = struct {
    /// The Zig expression for the field's start offset.
    expr: []const u8,
    /// The expression for the byte after the field.
    end: []const u8,
};

fn emitPackedReader(alloc: std.mem.Allocator, name: []const u8, ty: schema.Type, infos: []const FieldInfo, w: anytype) !void {
    try emit(w,
        \\pub const ${name}Reader = struct {
        \\    const Self = @This();
        \\    /// The record's bytes, from its first field. A packed record is
        \\    /// trusted (zbuf.load): its container checks it whole, so the
        \\    /// fields are read where the layout puts them, when asked for.
        \\    buf: []const u8,
        \\
        \\
    , .{ .name = name });
    if (schema.packedFixedSize(ty)) |sz| {
        try emit(w, "    pub const SIZE: u32 = $size;\n\n", .{ .size = sz });
    }
    try w.writeAll(
        \\    pub fn init(buf: []const u8) Self {
        \\        return .{ .buf = buf };
        \\    }
        \\
        \\
    );

    // Field starts: constants for the fixed prefix, functions after.
    const pos = try alloc.alloc(FieldPos, infos.len);
    defer alloc.free(pos);
    defer for (pos) |p| {
        alloc.free(p.expr);
        alloc.free(p.end);
    };
    var static: ?u32 = 0;
    for (infos, 0..) |info, i| {
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        if (static) |off| {
            pos[i].expr = try std.fmt.allocPrint(alloc, "{s}_off", .{info.name});
            try emit(w, "    const ${field}_off: u32 = $off;\n", .{ .field = info.name, .off = off });
        } else {
            // The previous field's start, bound once, then its end.
            pos[i].expr = try std.fmt.allocPrint(alloc, "self.{s}Off()", .{getter});
            try emit(w,
                \\    fn ${getter}Off(self: Self) u32 {
                \\        const at = $prev;
                \\        return $prev_end;
                \\    }
                \\
            , .{ .getter = getter, .prev = pos[i - 1].expr, .prev_end = pos[i - 1].end });
        }
        // Where this field ends, as an expression over `at`, its start.
        if (info.fixed) |sz| {
            pos[i].end = try std.fmt.allocPrint(alloc, "at + {d}", .{sz});
            if (static) |off| static = off + sz;
        } else if (info.ty.kind == .bytes and info.len == .rest) {
            pos[i].end = try alloc.dupe(u8, "@as(u32, @intCast(self.buf.len))");
            static = null;
        } else if (info.ty.kind == .bytes) {
            pos[i].end = try std.fmt.allocPrint(alloc, "at + {d} + zbuf.packedArrayLen(self.buf, at, {s})", .{ info.len.bytes(), lenWidthName(info.len) });
            static = null;
        } else if (schema.packedFixedSize(info.ty.elem())) |elem| {
            pos[i].end = try std.fmt.allocPrint(alloc, "at + {d} + {d} * zbuf.packedArrayLen(self.buf, at, {s})", .{ info.len.bytes(), elem, lenWidthName(info.len) });
            static = null;
        } else {
            pos[i].end = try std.fmt.allocPrint(alloc, "zbuf.packedRecordsEnd(self.buf, at, {s})", .{lenWidthName(info.len)});
            static = null;
        }
    }
    // A fixed record's size is its SIZE, and reads nothing.
    if (static != null) {
        try w.writeAll(
            \\
            \\    /// Bytes the record spans.
            \\    pub fn size(_: Self) u32 {
            \\        return SIZE;
            \\    }
            \\
            \\
        );
    } else if (infos[infos.len - 1].ty.kind == .bytes and infos[infos.len - 1].len == .rest) {
        // A record ending in the rest spans its whole buffer.
        try w.writeAll(
            \\
            \\    /// Bytes the record spans: to the end of its buffer.
            \\    pub fn size(self: Self) u32 {
            \\        return @intCast(self.buf.len);
            \\    }
            \\
            \\
        );
    } else {
        try emit(w,
            \\
            \\    /// Bytes the record spans, from its start to after its last field.
            \\    pub fn size(self: Self) u32 {
            \\        const at = $last;
            \\        return $end;
            \\    }
            \\
            \\
        , .{ .last = pos[infos.len - 1].expr, .end = pos[infos.len - 1].end });
    }

    for (infos, 0..) |info, i| {
        const getter = try schema.camelName(alloc, info.name);
        defer alloc.free(getter);
        const off = pos[i].expr;
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64 => try emit(w,
                \\    pub fn $getter(self: Self) $ty {
                \\        return zbuf.load($ty, self.buf, $off);
                \\    }
                \\
                \\
            , .{ .getter = getter, .ty = scalar(info.ty.kind).ty, .off = off }),
            .enum_ => try emit(w,
                \\    pub fn $getter(self: Self) ${enum}Enum {
                \\        return @enumFromInt(self.buf[$off]);
                \\    }
                \\
                \\
            , .{ .getter = getter, .@"enum" = try enumName(info.ty), .off = off }),
            .bytes => if (info.len == .rest) {
                try emit(w,
                    \\    pub fn $getter(self: Self) []const u8 {
                    \\        return self.buf[$off..];
                    \\    }
                    \\
                    \\
                , .{ .getter = getter, .off = off });
            } else {
                try emit(w,
                    \\    pub fn $getter(self: Self) []const u8 {
                    \\        return zbuf.packedBytes(self.buf, $off, $width);
                    \\    }
                    \\
                    \\
                , .{ .getter = getter, .off = off, .width = lenWidthName(info.len) });
            },
            .packed_ => try emit(w,
                \\    pub fn $getter(self: Self) ${child}Reader {
                \\        return ${child}Reader.init(self.buf[$off..][0..${child}Reader.SIZE]);
                \\    }
                \\
                \\
            , .{ .getter = getter, .child = try packedName(info.ty), .off = off }),
            .array => {
                const child = info.ty.elem();
                try emit(w,
                    \\    pub fn ${getter}Len(self: Self) u32 {
                    \\        return zbuf.packedArrayLen(self.buf, $off, $width);
                    \\    }
                    \\
                    \\
                , .{ .getter = getter, .off = off, .width = lenWidthName(info.len) });
                const elem = schema.packedFixedSize(child) orelse {
                    // Variable-size records behind their end-offset table.
                    try emit(w,
                        \\    pub fn ${getter}At(self: Self, i: u32) Error!${child}Reader {
                        \\        return ${child}Reader.init(try zbuf.packedRecord(self.buf, $off, $width, i));
                        \\    }
                        \\
                        \\
                    , .{ .getter = getter, .child = try packedName(child), .off = off, .width = lenWidthName(info.len) });
                    continue;
                };
                if (child.kind == .packed_) {
                    try emit(w,
                        \\    pub fn ${getter}At(self: Self, i: u32) Error!${child}Reader {
                        \\        return ${child}Reader.init(try zbuf.packedElem(self.buf, $off, $width, $elem, i));
                        \\    }
                        \\
                        \\
                    , .{ .getter = getter, .child = try packedName(child), .off = off, .width = lenWidthName(info.len), .elem = elem });
                } else {
                    const ty_name = scalar(child.kind).ty;
                    try emit(w,
                        \\    pub fn ${getter}At(self: Self, i: u32) Error!$ty {
                        \\        return zbuf.load($ty, try zbuf.packedElem(self.buf, $off, $width, $elem, i), 0);
                        \\    }
                        \\
                        \\    pub fn ${getter}ToSliceAlloc(self: Self, alloc: std.mem.Allocator) Error![]$ty {
                        \\        return zbuf.packedToSliceAlloc($ty, self.buf, $off, $width, alloc);
                        \\    }
                        \\
                        \\
                    , .{ .getter = getter, .ty = ty_name, .off = off, .width = lenWidthName(info.len), .elem = elem });
                }
            },
            .table, .bool => unreachable,
        }
    }

    try emitToStruct(alloc, name, infos, w);
    try w.writeAll("};\n\n");
}

fn emitPackedWriter(name: []const u8, ty: schema.Type, infos: []const FieldInfo, w: anytype) !void {
    try emit(w,
        \\pub const ${name}Writer = struct {
        \\    const Self = @This();
        \\    w: zbuf.PackedWriter,
        \\
        \\
    , .{ .name = name });
    if (schema.packedFixedSize(ty)) |sz| {
        try emit(w, "    pub const SIZE: u32 = $size;\n\n", .{ .size = sz });
    }
    try w.writeAll(
        \\    /// The record is appended to `buf` from its current end.
        \\    pub fn initWithBuf(alloc: std.mem.Allocator, buf: *std.ArrayList(u8)) Self {
        \\        return .{ .w = zbuf.PackedWriter.initWithBuf(alloc, buf) };
        \\    }
        \\
        \\    /// Every field, in order, from a struct literal or a *Struct: a
        \\    /// packed record is positional, so none may be left out. Call once.
        \\    pub fn set(self: *Self, values: anytype) Error!void {
        \\        const Values = @TypeOf(values);
        \\        if (@typeInfo(Values) != .@"struct") @compileError("set() expects a struct like .{ .field = value }");
        \\
    );
    for (infos) |info| {
        try emit(w,
            \\        if (!@hasField(Values, "$field")) @compileError("packed set() needs every field; missing: $field");
            \\
        , .{ .field = info.name });
    }
    for (infos) |info| {
        switch (info.ty.kind) {
            .u8, .u16, .u32, .u64 => try emit(w,
                \\        try self.w.int($ty, values.$field);
                \\
            , .{ .ty = scalar(info.ty.kind).ty, .field = info.name }),
            .enum_ => try emit(w,
                \\        const ${field}_v: ${enum}Enum = values.$field;
                \\        try self.w.int(u8, @intFromEnum(${field}_v));
                \\
            , .{ .field = info.name, .@"enum" = try enumName(info.ty) }),
            .bytes => if (info.len == .rest) {
                try emit(w, "        try self.w.rest(values.$field);\n", .{ .field = info.name });
            } else {
                try emit(w, "        try self.w.bytes($width, values.$field);\n", .{ .width = lenWidthName(info.len), .field = info.name });
            },
            // A nested value is written as given: a literal must name
            // every field of the child, like `set` itself.
            .packed_ => try emit(w,
                \\        {
                \\            var child = ${child}Writer.initWithBuf(self.w.alloc, self.w.buf);
                \\            try child.set(values.$field);
                \\            _ = child.finish();
                \\        }
                \\
            , .{ .child = try packedName(info.ty), .field = info.name }),
            .array => {
                const child = info.ty.elem();
                if (child.kind == .packed_ and schema.packedFixedSize(child) == null) {
                    try emit(w,
                        \\        var ${field}_tbl = try self.w.records($width, values.$field.len);
                        \\        for (values.$field) |elem| {
                        \\            var child = ${child}Writer.initWithBuf(self.w.alloc, self.w.buf);
                        \\            try child.set(elem);
                        \\            _ = child.finish();
                        \\            ${field}_tbl.endRecord(&self.w);
                        \\        }
                        \\
                    , .{ .width = lenWidthName(info.len), .field = info.name, .child = try packedName(child) });
                } else if (child.kind == .packed_) {
                    try emit(w,
                        \\        try self.w.count($width, values.$field.len);
                        \\        for (values.$field) |elem| {
                        \\            var child = ${child}Writer.initWithBuf(self.w.alloc, self.w.buf);
                        \\            try child.set(elem);
                        \\            _ = child.finish();
                        \\        }
                        \\
                    , .{ .width = lenWidthName(info.len), .field = info.name, .child = try packedName(child) });
                } else {
                    try emit(w,
                        \\        try self.w.ints($ty, $width, values.$field);
                        \\
                    , .{ .ty = scalar(child.kind).ty, .width = lenWidthName(info.len), .field = info.name });
                }
            },
            .table, .bool => unreachable,
        }
    }
    try w.writeAll(
        \\    }
        \\
        \\    /// The record's start offset in the buffer.
        \\    pub fn finish(self: *Self) u32 {
        \\        return self.w.finish();
        \\    }
        \\};
        \\
        \\
    );
}
